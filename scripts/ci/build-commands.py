#!/usr/bin/env python3
"""Inline workflow text into multi-file commands, or check that it is current.

A command that only says "read these files" costs one model turn per file.
Measured with `claude plugin eval` on craft: 9 turns -> 4 and about a third
less cost with the text inlined, at the same score. The skills/ files stay
the source of truth; this script copies their bodies between the markers.

    python3 scripts/ci/build-commands.py          # rewrite commands/*.md
    python3 scripts/ci/build-commands.py --check  # exit 1 when out of date

Every generated command must also fit its byte budget in
scripts/ci/command-budget.json. Raising a budget is a reviewed decision in the
same diff: say what the added text is worth, or remove something else.
"""
from __future__ import annotations

import json
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BEGIN = "<!-- BEGIN INLINED WORKFLOW (generated by scripts/ci/build-commands.py; edit skills/, not this block) -->"
END = "<!-- END INLINED WORKFLOW -->"
LEAD = (
    "The files below are inlined in full. Execute them as written and do not read\n"
    "them again. Read any other file they name only when the task needs it."
)
# Specific workflow first: after context compaction only the head is re-attached.
COMMANDS = {
    "craft": ["workflow/craft.md", "workflow/gates.md", "principles/oop-discipline.md"],
    "refactor": ["workflow/refactor.md", "workflow/gates.md", "principles/oop-discipline.md"],
    "test": ["workflow/test.md", "workflow/gates.md"],
    "crucible": ["workflow/crucible.md", "workflow/gates.md"],
}


def body(relative: str) -> str:
    text = (ROOT / "skills" / relative).read_text(encoding="utf-8")
    # The command loader rewrites these in a command body, so they must not
    # arrive from a skill file: argument placeholders and shell injection.
    for pattern in (r"\$\d", r"\$ARGUMENTS", r"\$\{CLAUDE_", r"(^|\s)!`", r"^```!"):
        if re.search(pattern, text, re.M):
            raise SystemExit(f"skills/{relative}: {pattern!r} would be rewritten when inlined")
    text = text.split("---", 2)[2] if text.startswith("---") else text
    source_dir = (ROOT / "skills" / relative).parent

    def relink(match: re.Match) -> str:
        # A link relative to skills/<dir>/ must still resolve from commands/.
        target = os.path.relpath(source_dir / match.group(1), ROOT / "commands")
        return f"]({target}{match.group(2) or ''})"

    text = re.sub(r"\]\((?!https?:|#|/)([^)#\s]+\.md)(#[^)]*)?\)", relink, text)
    return "\n".join(line.rstrip() for line in text.strip().splitlines())


def render(files: list[str]) -> str:
    parts = [BEGIN, "", LEAD, ""]
    for relative in files:
        parts += [f"<!-- skills/{relative} -->", body(relative), ""]
    return "\n".join(parts + [END])


def build(name: str, files: list[str]) -> tuple[pathlib.Path, str, str]:
    path = ROOT / "commands" / f"{name}.md"
    current = path.read_text(encoding="utf-8")
    block = render(files)
    if BEGIN in current:
        head, rest = current.split(BEGIN, 1)
        updated = head + block + rest.split(END, 1)[1]
    else:
        marker = "User request:"
        if current.count(marker) != 1:
            raise SystemExit(f"commands/{name}.md: expected one {marker!r}")
        updated = current.replace(marker, block + "\n\n" + marker)
    return path, current, updated


BUDGET_FILE = ROOT / "scripts" / "ci" / "command-budget.json"


def over_budget() -> list[str]:
    budgets = json.loads(BUDGET_FILE.read_text(encoding="utf-8"))
    over = []
    for name in sorted((ROOT / "commands").glob("*.md")):
        size = len(name.read_bytes())
        limit = budgets.get(name.stem)
        if limit is None:
            over.append(f"{name.name}: no budget in {BUDGET_FILE.name}")
        elif size > limit:
            over.append(f"{name.name}: {size} bytes > budget {limit}")
    return over


def main() -> None:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, files in COMMANDS.items():
        path, current, updated = build(name, files)
        if current != updated:
            stale.append(path.name)
            if not check:
                path.write_text(updated, encoding="utf-8")
    if check and stale:
        raise SystemExit(
            "commands out of date: " + ", ".join(stale)
            + " - run python3 scripts/ci/build-commands.py"
        )
    print("commands current" if not stale else "rewrote " + ", ".join(stale))
    over = over_budget()
    if over:
        raise SystemExit("command budget exceeded: " + "; ".join(over))


if __name__ == "__main__":
    main()
